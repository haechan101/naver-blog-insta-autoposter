# 화면에 보여줄 순서 (자료가 넉넉한 주제부터)
DISPLAY_ORDER = ["resume", "ncs", "interview", "company", "caution", "qna"]


def get(key: str) -> dict:
    """주제 정의를 돌려줍니다. 'all' 이면 종합 정리."""
    return ALL_TOPIC if key == ALL_KEY else TOPICS[key]


def name(key: str) -> str:
    return get(key)["name"]


def availability(chars: int, key: str) -> str:
    """원문 분량 → 'ok'(가능) / 'thin'(제한적) / 'none'(자료 부족)."""
    if key == ALL_KEY:
        return "ok"
    lo = TOPICS[key]["min_chars"]
    if chars >= lo:
        return "ok"
    if chars >= round(lo * 0.4):
        return "thin"
    return "none"
